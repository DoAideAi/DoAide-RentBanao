def calculate_stamp_duty(state_key: str, monthly_rent: float, security_deposit: float, duration_months: int) -> dict:
    state = STAMP_DUTY_DATA.get(state_key)
    if not state:
        return {"error": "State not found"}

    annual_rent = monthly_rent * 12
    total_rent = monthly_rent * duration_months

    if state["stamp_duty_percent"] > 0:
        if state_key == "maharashtra":
            calculated = (total_rent + security_deposit) * state["stamp_duty_percent"] / 100
        elif state_key == "delhi":
            calculated = (total_rent + security_deposit) * state["stamp_duty_percent"] / 100
        else:
            calculated = annual_rent * state["stamp_duty_percent"] / 100
        stamp_duty = max(calculated, state["stamp_duty_fixed"])
    else:
        stamp_duty = state["stamp_duty_fixed"]

    stamp_duty = round(stamp_duty)
    registration_fee = state["registration_fee"] if (
        state["registration_required"] and duration_months > state["max_lease_without_registration"]
    ) else 0

    return {
        "state": state["name"],
        "stamp_duty": stamp_duty,
        "stamp_duty_rate": state["stamp_duty_rate"],
        "registration_fee": registration_fee,
        "registration_required": state["registration_required"] and duration_months > state["max_lease_without_registration"],
        "total_cost": stamp_duty + registration_fee,
        "e_stamp_available": state["e_stamp_available"],
        "notes": state["notes"],
        "annual_rent": annual_rent,
        "total_rent": total_rent,
    }
